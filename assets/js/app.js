/*
 * Codzienne Spojrzenie - main application.
 * Loads the daily edition snapshot (data/edition.js: news + article images,
 * built by scripts/build_edition.py), renders the four "Gazeta" categories
 * and wires the audio player.
 */
(function () {
  "use strict";

  var cfg = window.CC_CONFIG;
  var CATS = cfg.categories;
  var EDITION_FILE = "data/edition.js";
  var EDITION_CACHE_KEY = "cc:edition:v2";

  var $ = function (id) { return document.getElementById(id); };

  var state = {
    feeds: { general: [], tech: [] },
    dates: { general: "", tech: "" },
    active: CATS[0].id,
    loaded: false,
    failed: false,
    fromCache: false,
    current: [],
    generated: ""
  };

  // =========================================================================
  // Helpers
  // =========================================================================
  function lsGet(key, fallback) {
    try {
      var v = localStorage.getItem(key);
      return v == null ? fallback : JSON.parse(v);
    } catch (e) { return fallback; }
  }
  function lsSet(key, value) {
    try { localStorage.setItem(key, JSON.stringify(value)); } catch (e) { /* ignore */ }
  }

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }

  function safeUrl(u) {
    try {
      var url = new URL(String(u || "").trim());
      return url.protocol === "https:" || url.protocol === "http:" ? url.href : "";
    } catch (e) { return ""; }
  }

  function hostOf(u) {
    try { return new URL(u).hostname.replace(/^www\./, ""); } catch (e) { return ""; }
  }

  function paragraphs(text) {
    return String(text || "").split(/\n+/).map(function (p) { return p.trim(); })
      .filter(Boolean).map(function (p) { return "<p>" + esc(p) + "</p>"; }).join("");
  }

  /** Polish plural: 1 artykuł, 2-4 artykuły, 5+ artykułów (12-14 -> artykułów). */
  function plural(n, one, few, many) {
    if (n === 1) return one;
    var d = n % 10, dd = n % 100;
    return d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? few : many;
  }

  function capitalize(s) { return s ? s.charAt(0).toUpperCase() + s.slice(1) : s; }

  /** Meta file format: DDMMYYYY (e.g. "09112026"). */
  function parseEditionDate(raw) {
    var m = /^(\d{2})(\d{2})(\d{4})$/.exec(String(raw || "").trim());
    if (!m) return null;
    var d = new Date(+m[3], +m[2] - 1, +m[1]);
    return isNaN(d) ? null : d;
  }

  var longDate = new Intl.DateTimeFormat("pl-PL", { weekday: "long", day: "numeric", month: "long", year: "numeric" });
  var shortDate = new Intl.DateTimeFormat("pl-PL", { day: "numeric", month: "long" });

  function sameDay(a, b) {
    return a.getFullYear() === b.getFullYear() && a.getMonth() === b.getMonth() && a.getDate() === b.getDate();
  }

  function todayKey() {
    var d = new Date();
    return String(d.getDate()).padStart(2, "0") + "/" + String(d.getMonth() + 1).padStart(2, "0") + "/" + d.getFullYear();
  }

  function catById(id) {
    for (var i = 0; i < CATS.length; i++) if (CATS[i].id === id) return CATS[i];
    return CATS[0];
  }

  function catBySlug(slug) {
    for (var i = 0; i < CATS.length; i++) if (CATS[i].slug === slug || CATS[i].id === slug) return CATS[i];
    return null;
  }

  function itemsFor(cat) {
    var feed = state.feeds[cat.feed] || [];
    return cat.wholeFeed ? feed : feed.filter(function (i) { return i.category === cat.id; });
  }

  function hasOpinions(item) {
    var o = (item.opinions || "").trim();
    return !!o && !/chwilowo niedostępne|brak opinii/i.test(o);
  }

  // =========================================================================
  // Toast
  // =========================================================================
  var toastTimer;
  function toast(message, action) {
    var t = $("toast");
    t.innerHTML = "<span>" + esc(message) + "</span>";
    if (action) {
      var b = document.createElement("button");
      b.type = "button";
      b.textContent = action.label;
      b.addEventListener("click", function () { t.classList.remove("is-visible"); action.fn(); });
      t.appendChild(b);
    }
    t.classList.add("is-visible");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(function () { t.classList.remove("is-visible"); }, action ? 9000 : 2600);
  }

  // =========================================================================
  // Data loading
  //   data/edition.js is generated by scripts/build_edition.py (GitHub Action,
  //   hourly check): news + article images of the current edition.
  //   Loaded as a <script> so the page also works when opened from disk.
  // =========================================================================
  function loadScript(src, timeoutMs) {
    return new Promise(function (resolve, reject) {
      var s = document.createElement("script");
      var timer = setTimeout(function () { s.remove(); reject(new Error("Timeout: " + src)); }, timeoutMs || 20000);
      s.onload = function () { clearTimeout(timer); s.remove(); resolve(); };
      s.onerror = function () { clearTimeout(timer); s.remove(); reject(new Error("Cannot load " + src)); };
      s.src = src;
      document.head.appendChild(s);
    });
  }

  function normalizeItem(o) {
    return {
      title: String(o.title || "").trim(),
      summary: String(o.summary || "").trim(),
      category: String(o.news_category || "").trim(),
      score: Number(o.score) || 0,
      url: safeUrl(o.source_url),
      opinions: String(o.opinions || "").trim(),
      image: safeUrl(o.image)
    };
  }

  function normalizeFeed(list) {
    return (Array.isArray(list) ? list : []).map(normalizeItem).filter(function (i) { return i.title; });
  }

  function loadEdition() {
    state.failed = false;
    window.CC_EDITION = null;
    // Cache-buster: always get the latest snapshot, never a stale browser copy.
    return loadScript(EDITION_FILE + "?v=" + Date.now()).then(function () {
      var ed = window.CC_EDITION;
      if (!ed || !ed.feeds) throw new Error("Invalid edition file");
      var general = normalizeFeed(ed.feeds.general);
      var tech = normalizeFeed(ed.feeds.tech);
      state.generated = ed.generated || "";
      applyEdition(general, tech, ed.dates || {}, false);
      hideNotice();
      lsSet(EDITION_CACHE_KEY, { generated: state.generated, dates: ed.dates || {}, general: general, tech: tech });
    }).catch(function (err) {
      console.error(err);
      var cached = lsGet(EDITION_CACHE_KEY, null);
      if (cached && cached.general) {
        state.generated = cached.generated || "";
        applyEdition(cached.general, cached.tech, cached.dates || {}, true);
        showNotice("Brak połączenia — wyświetlamy ostatnio zapisane wydanie.", true);
      } else {
        state.failed = true;
        state.loaded = true;
        renderAll();
      }
    });
  }

  function applyEdition(general, tech, dates, fromCache) {
    state.feeds.general = general || [];
    state.feeds.tech = tech || [];
    state.dates = dates || {};
    state.fromCache = fromCache;
    state.loaded = true;
    state.lastCheck = Date.now();

    var edition = state.dates.general || state.dates.tech || "";
    var date = parseEditionDate(edition);
    window.CCPlayer.setEdition(edition, date ? capitalize(longDate.format(date)) : "");
    renderAll();
  }

  /** Called periodically: offers a reload when a newer snapshot has been published. */
  function checkForUpdate() {
    if (!state.loaded || document.hidden || location.protocol === "file:") return;
    state.lastCheck = Date.now();
    fetch(EDITION_FILE + "?t=" + Date.now(), { cache: "no-store" })
      .then(function (r) {
        if (!r.ok) throw new Error("HTTP " + r.status);
        return r.text();
      })
      .then(function (text) {
        var m = /"generated":\s*"([^"]+)"/.exec(text);
        if (m && state.generated && m[1] !== state.generated) {
          toast("Dostępne jest nowe wydanie.", { label: "Odśwież", fn: function () { location.reload(); } });
        }
      })
      .catch(function () { /* offline: try later */ });
  }

  // =========================================================================
  // Rendering: hero / stats
  // =========================================================================
  function renderHero() {
    var now = new Date();
    $("today-date").textContent = capitalize(longDate.format(now));
    $("year").textContent = now.getFullYear();

    var fact = window.CC_CURIOSITIES && window.CC_CURIOSITIES[todayKey()];
    if (fact) {
      $("fact-text").textContent = fact;
      $("fact").hidden = false;
    }

    var line = $("edition-line");
    if (!state.loaded) return;
    if (state.failed) { line.textContent = "Wydanie chwilowo niedostępne"; return; }

    var date = parseEditionDate(state.dates.general || state.dates.tech);
    if (date) {
      var yesterday = new Date(now); yesterday.setDate(now.getDate() - 1);
      var label = sameDay(date, now) ? "dzisiejsze wydanie"
        : sameDay(date, yesterday) ? "wczorajsze wydanie" : "najnowsze dostępne wydanie";
      line.innerHTML = "<strong>" + esc(capitalize(longDate.format(date))) + "</strong> · " + label;
      $("footer-updated").textContent = "Wydanie z " + shortDate.format(date) + " " + date.getFullYear();
    } else {
      line.textContent = "Najnowsze wydanie";
    }

    var total = state.feeds.general.length + state.feeds.tech.length;
    $("stat-total").textContent = total;
  }

  function renderAudioStat(durations) {
    var sum = (durations.general || 0) + (durations.tech || 0);
    if (sum > 0) $("stat-audio").textContent = Math.round(sum / 60);
  }

  // =========================================================================
  // Rendering: tabs
  // =========================================================================
  function renderTabs() {
    var html = CATS.map(function (c) {
      var selected = c.id === state.active;
      var count = state.loaded && !state.failed ? itemsFor(c).length : "–";
      return '<button class="tab" type="button" role="tab" id="tab-' + c.id + '" data-cat="' + c.id + '"' +
        ' aria-selected="' + selected + '" aria-controls="news" tabindex="' + (selected ? 0 : -1) + '">' +
        '<svg class="icon" aria-hidden="true"><use href="#' + c.icon + '"/></svg>' +
        esc(c.label) + '<span class="tab__count">' + count + "</span></button>";
    }).join("");
    $("tablist").innerHTML = html;
  }

  function selectCategory(id, opts) {
    opts = opts || {};
    if (id === state.active && !opts.force) return;
    state.active = id;
    var cat = catById(id);

    var tabs = $("tablist").querySelectorAll(".tab");
    Array.prototype.forEach.call(tabs, function (t) {
      var sel = t.dataset.cat === id;
      t.setAttribute("aria-selected", sel);
      t.tabIndex = sel ? 0 : -1;
      if (sel) {
        var list = $("tablist");
        if (t.offsetLeft < list.scrollLeft || t.offsetLeft + t.offsetWidth > list.scrollLeft + list.clientWidth) {
          list.scrollTo({ left: t.offsetLeft - 24, behavior: "smooth" });
        }
        if (opts.focus) t.focus();
      }
    });

    try { history.replaceState(null, "", "#" + cat.slug); } catch (e) { /* file:// in some browsers */ }
    renderNews();

    // Like the app: jump back to the top of the list when switching categories.
    var news = $("news");
    var tabsH = document.querySelector(".tabs").offsetHeight;
    if (opts.scroll !== false && news.getBoundingClientRect().top < tabsH) {
      window.scrollTo({ top: window.scrollY + news.getBoundingClientRect().top - tabsH, behavior: "smooth" });
    }
  }

  // =========================================================================
  // Rendering: news
  // =========================================================================
  function skeletonHTML() {
    var card = '<div class="skeleton"><div class="skeleton__block skeleton__img"></div>' +
      '<div class="skeleton__block skeleton__line skeleton__line--title"></div>' +
      '<div class="skeleton__block skeleton__line"></div><div class="skeleton__block skeleton__line"></div>' +
      '<div class="skeleton__block skeleton__line skeleton__line--short"></div></div>';
    return '<div class="news__grid" style="margin-top:0">' + card + card + card + "</div>";
  }

  function storyHTML(item, i, cat, isLead) {
    var host = item.url ? hostOf(item.url) : "";
    var num = String(i + 1).padStart(2, "0");
    var opinions = hasOpinions(item);

    var kicker = '<p class="story__kicker">' +
      (isLead ? '<span class="badge">Najważniejsze</span>' : '<span class="story__num">' + num + "</span>") +
      (host ? '<span class="source"><img class="source__icon" src="https://www.google.com/s2/favicons?domain=' +
        encodeURIComponent(host) + '&sz=32" alt="" width="16" height="16" loading="lazy" referrerpolicy="no-referrer" onerror="this.remove()">' +
        '<span class="source__name">' + esc(host) + "</span></span>" : "") +
      "</p>";

    var title = item.url
      ? '<a href="' + esc(item.url) + '" target="_blank" rel="noopener noreferrer">' + esc(item.title) + "</a>"
      : esc(item.title);

    var actions = '<div class="story__actions">' +
      (item.url
        ? '<a class="read-link" href="' + esc(item.url) + '" target="_blank" rel="noopener noreferrer">Czytaj źródło<svg class="icon" aria-hidden="true"><use href="#i-external"/></svg></a>'
        : '<span class="read-link" aria-disabled="true">Brak źródła</span>') +
      '<div class="story__icons">' +
      '<button class="icon-btn" type="button" data-action="copy" data-i="' + i + '" aria-label="Kopiuj artykuł" title="Kopiuj"><svg class="icon"><use href="#i-copy"/></svg></button>' +
      '<button class="icon-btn" type="button" data-action="share" data-i="' + i + '" aria-label="Udostępnij artykuł" title="Udostępnij"><svg class="icon"><use href="#i-share"/></svg></button>' +
      '<button class="icon-btn" type="button" data-action="opinions" data-i="' + i + '"' +
      (opinions ? ' aria-label="Opinie społeczności" title="Opinie społeczności"' : ' disabled aria-label="Opinie niedostępne" title="Opinie niedostępne"') +
      '><svg class="icon"><use href="#i-comment"/></svg></button>' +
      "</div></div>";

    return '<article class="story' + (isLead ? " story--lead" : "") + '" data-cat="' + cat.id + '" style="animation-delay:' + Math.min(i, 8) * 40 + 'ms">' +
      '<div class="story__media"><div class="thumb is-loading" data-i="' + i + '"></div></div>' +
      '<div class="story__body">' + kicker +
      '<h3 class="story__title">' + title + "</h3>" +
      '<div class="story__summary">' + paragraphs(item.summary) + "</div>" +
      actions + "</div></article>";
  }

  function renderNews() {
    var cat = catById(state.active);
    var list = $("news-list");
    var newsEl = $("news");
    newsEl.dataset.cat = cat.id;
    newsEl.setAttribute("aria-labelledby", "tab-" + cat.id);
    $("news-title").textContent = cat.label;

    var date = parseEditionDate(state.dates.general || state.dates.tech);
    $("news-eyebrow").textContent = "Gazeta" + (date ? " · " + shortDate.format(date) : "");

    if (!state.loaded) {
      list.setAttribute("aria-busy", "true");
      list.innerHTML = skeletonHTML();
      $("news-count").textContent = "";
      return;
    }
    list.setAttribute("aria-busy", "false");

    if (state.failed) {
      $("news-count").textContent = "";
      list.innerHTML = '<div class="error-box"><h3>Nie udało się pobrać wiadomości</h3>' +
        "<p>Sprawdź połączenie z internetem i spróbuj ponownie.</p>" +
        '<button class="btn btn--accent" type="button" id="retry"><svg class="icon"><use href="#i-refresh"/></svg>Spróbuj ponownie</button></div>';
      $("retry").addEventListener("click", function () {
        state.loaded = false;
        renderAll();
        loadEdition();
      });
      return;
    }

    var items = itemsFor(cat);
    state.current = items;
    $("news-count").textContent = items.length + " " + plural(items.length, "artykuł", "artykuły", "artykułów");

    if (!items.length) {
      list.innerHTML = '<div class="empty">Brak dostępnych wiadomości w tej kategorii.</div>';
      return;
    }

    var html = storyHTML(items[0], 0, cat, true);
    if (items.length > 1) {
      html += '<div class="news__grid">' + items.slice(1).map(function (it, k) {
        return storyHTML(it, k + 1, cat, false);
      }).join("") + "</div>";
    }
    list.innerHTML = html;

    Array.prototype.forEach.call(list.querySelectorAll(".thumb"), function (el) {
      hydrateThumb(el, items[+el.dataset.i], cat, el.dataset.i === "0");
    });
  }

  function renderAll() {
    renderHero();
    renderTabs();
    renderNews();
  }

  // =========================================================================
  // Images
  //   The image URL comes with each article in data/edition.js (extracted once
  //   per edition by the GitHub Action). No image, or it fails to load ->
  //   designed placeholder with the category icon and the source domain.
  // =========================================================================
  function hydrateThumb(el, item, cat, eager) {
    if (item.image) setImage(el, item.image, item, cat, eager);
    else setPlaceholder(el, item, cat);
  }

  function setImage(el, src, item, cat, eager) {
    var im = new Image();
    im.alt = "";
    im.decoding = "async";
    im.referrerPolicy = "no-referrer"; // avoids hot-link blocks on many news sites
    im.loading = eager ? "eager" : "lazy";
    im.onload = function () {
      if (im.naturalWidth && im.naturalWidth < 80) return setPlaceholder(el, item, cat);
      el.classList.remove("is-loading");
      el.classList.add("is-loaded");
      el.tabIndex = 0;
      el.setAttribute("role", "button");
      el.setAttribute("aria-label", "Powiększ zdjęcie: " + item.title);
      el.dataset.full = src;
    };
    im.onerror = function () { setPlaceholder(el, item, cat); };
    el.innerHTML = "";
    el.appendChild(im);
    im.src = src;
  }

  function setPlaceholder(el, item, cat) {
    var host = item.url ? hostOf(item.url) : "";
    el.className = "thumb thumb--empty";
    el.removeAttribute("role");
    el.removeAttribute("tabindex");
    el.innerHTML = '<svg class="icon thumb__icon" aria-hidden="true"><use href="#' + cat.icon + '"/></svg>' +
      '<span class="thumb__label"><small>' + esc(cat.label) + "</small>" + esc(host || cfg.siteName) + "</span>";
  }

  // =========================================================================
  // Article actions (copy / share / opinions / zoom)
  // =========================================================================
  function articleText(item) {
    return item.title + "\n\n" + item.summary + (item.url ? "\n\nŹródło: " + item.url : "");
  }

  function copyText(text) {
    if (navigator.clipboard && window.isSecureContext) {
      return navigator.clipboard.writeText(text).catch(function () { return legacyCopy(text); });
    }
    return legacyCopy(text);
  }

  function legacyCopy(text) {
    return new Promise(function (resolve, reject) {
      var ta = document.createElement("textarea");
      ta.value = text;
      ta.setAttribute("readonly", "");
      ta.style.cssText = "position:fixed;top:-1000px;opacity:0";
      document.body.appendChild(ta);
      ta.select();
      var ok = false;
      try { ok = document.execCommand("copy"); } catch (e) { /* ignore */ }
      document.body.removeChild(ta);
      ok ? resolve() : reject(new Error("copy failed"));
    });
  }

  function copyArticle(item) {
    copyText(articleText(item))
      .then(function () { toast("Skopiowano do schowka"); })
      .catch(function () { toast("Nie udało się skopiować"); });
  }

  function shareArticle(item) {
    if (navigator.share) {
      navigator.share({ title: item.title, text: item.title + "\n\n" + item.summary, url: item.url || undefined })
        .catch(function (e) { if (e && e.name !== "AbortError") copyArticle(item); });
    } else {
      copyText(articleText(item))
        .then(function () { toast("Skopiowano treść i link — możesz je wkleić i udostępnić"); })
        .catch(function () { toast("Udostępnianie nie jest dostępne w tej przeglądarce"); });
    }
  }

  function openDialog(d) {
    if (typeof d.showModal === "function") d.showModal(); else d.setAttribute("open", "");
  }
  function closeDialog(d) {
    if (typeof d.close === "function") d.close(); else d.removeAttribute("open");
  }

  function showOpinions(item) {
    $("opinions-title").textContent = item.title;
    $("opinions-body").innerHTML = paragraphs(item.opinions) || "<p>Brak opinii społeczności dla tego artykułu.</p>";
    openDialog($("opinions-dialog"));
  }

  function showImage(src, item) {
    $("lightbox-img").src = src;
    $("lightbox-img").alt = item.title;
    $("lightbox-caption").textContent = item.title + (item.url ? " — " + hostOf(item.url) : "");
    openDialog($("image-dialog"));
  }

  // =========================================================================
  // Notice bar
  // =========================================================================
  function showNotice(text, withRetry) {
    var n = $("notice");
    n.innerHTML = "<span>" + esc(text) + "</span>" +
      (withRetry ? '<button class="btn btn--outline" type="button" id="notice-retry">Odśwież</button>' : "");
    n.hidden = false;
    var r = $("notice-retry");
    if (r) r.addEventListener("click", function () { location.reload(); });
  }
  function hideNotice() { $("notice").hidden = true; }

  // =========================================================================
  // Preferences: theme + text size
  // =========================================================================
  var SCALES = [0.875, 1, 1.125, 1.25, 1.375];

  function currentScale() {
    var v = parseFloat(getComputedStyle(document.documentElement).getPropertyValue("--scale"));
    return isFinite(v) ? v : 1;
  }

  function setScale(dir) {
    var cur = currentScale();
    var idx = SCALES.indexOf(cur);
    if (idx === -1) idx = 1;
    idx = Math.max(0, Math.min(SCALES.length - 1, idx + dir));
    document.documentElement.style.setProperty("--scale", SCALES[idx]);
    try { localStorage.setItem("cc:scale", String(SCALES[idx])); } catch (e) {}
    $("text-smaller").disabled = idx === 0;
    $("text-bigger").disabled = idx === SCALES.length - 1;
  }

  function isDark() {
    var t = document.documentElement.getAttribute("data-theme");
    if (t) return t === "dark";
    return window.matchMedia && matchMedia("(prefers-color-scheme: dark)").matches;
  }

  function toggleTheme() {
    var next = isDark() ? "light" : "dark";
    document.documentElement.setAttribute("data-theme", next);
    try { localStorage.setItem("cc:theme", next); } catch (e) {}
  }

  // =========================================================================
  // Player <-> track cards
  // =========================================================================
  function renderTracks(s) {
    Array.prototype.forEach.call(document.querySelectorAll(".track"), function (row) {
      var key = row.dataset.track;
      var active = s.track === key;
      row.classList.toggle("is-active", active);
      row.classList.toggle("is-playing", active && s.playing);
      var btn = row.querySelector(".track__play");
      btn.classList.toggle("is-playing", active && s.playing);
      btn.setAttribute("aria-label", (active && s.playing ? "Wstrzymaj: " : "Odtwórz: ") + cfg.feeds[key].title);
      var d = s.durations[key];
      row.querySelector('[data-role="duration"]').textContent = d ? Math.max(1, Math.round(d / 60)) + " min" : "--:--";
      row.querySelector('[data-role="progress"]').style.width = (window.CCPlayer.progress(key) * 100).toFixed(1) + "%";
    });
    var all = $("play-all");
    var allPlaying = s.mode === "all" && s.playing;
    all.classList.toggle("is-playing", allPlaying);
    all.querySelector('[data-role="label"]').textContent = allPlaying ? "Wstrzymaj wydanie" : "Odtwórz całe wydanie";
    renderAudioStat(s.durations);
  }

  // =========================================================================
  // Events
  // =========================================================================
  function bindEvents() {
    $("tablist").addEventListener("click", function (e) {
      var tab = e.target.closest(".tab");
      if (tab) selectCategory(tab.dataset.cat);
    });

    $("tablist").addEventListener("keydown", function (e) {
      var keys = ["ArrowLeft", "ArrowRight", "Home", "End"];
      if (keys.indexOf(e.key) === -1) return;
      e.preventDefault();
      var idx = CATS.findIndex(function (c) { return c.id === state.active; });
      if (e.key === "ArrowLeft") idx = (idx - 1 + CATS.length) % CATS.length;
      if (e.key === "ArrowRight") idx = (idx + 1) % CATS.length;
      if (e.key === "Home") idx = 0;
      if (e.key === "End") idx = CATS.length - 1;
      selectCategory(CATS[idx].id, { focus: true, scroll: false });
    });

    window.addEventListener("hashchange", function () {
      var cat = catBySlug(location.hash.slice(1));
      if (cat) selectCategory(cat.id);
    });

    $("news-list").addEventListener("click", function (e) {
      var btn = e.target.closest("[data-action]");
      if (btn) {
        var item = state.current[+btn.dataset.i];
        if (!item) return;
        if (btn.dataset.action === "copy") copyArticle(item);
        if (btn.dataset.action === "share") shareArticle(item);
        if (btn.dataset.action === "opinions") showOpinions(item);
        return;
      }
      var thumb = e.target.closest(".thumb.is-loaded");
      if (thumb) showImage(thumb.dataset.full, state.current[+thumb.dataset.i]);
    });

    $("news-list").addEventListener("keydown", function (e) {
      var thumb = e.target.closest && e.target.closest(".thumb.is-loaded");
      if (thumb && (e.key === "Enter" || e.key === " ")) {
        e.preventDefault();
        showImage(thumb.dataset.full, state.current[+thumb.dataset.i]);
      }
    });

    Array.prototype.forEach.call(document.querySelectorAll("dialog"), function (d) {
      d.addEventListener("click", function (e) {
        if (e.target === d || e.target.closest("[data-close]")) closeDialog(d);
      });
    });

    Array.prototype.forEach.call(document.querySelectorAll(".track"), function (row) {
      row.querySelector(".track__play").addEventListener("click", function () {
        window.CCPlayer.playTrack(row.dataset.track);
      });
    });
    $("play-all").addEventListener("click", function () { window.CCPlayer.playAll(); });

    $("text-smaller").addEventListener("click", function () { setScale(-1); });
    $("text-bigger").addEventListener("click", function () { setScale(1); });
    $("theme-toggle").addEventListener("click", toggleTheme);

    document.addEventListener("visibilitychange", function () {
      if (!document.hidden && Date.now() - (state.lastCheck || 0) > cfg.updateCheckMinutes * 60000) checkForUpdate();
    });
    setInterval(checkForUpdate, cfg.updateCheckMinutes * 60000);
  }

  // =========================================================================
  // Init
  // =========================================================================
  function init() {
    var fromHash = catBySlug(location.hash.slice(1));
    if (fromHash) state.active = fromHash.id;

    $("play-store").href = cfg.playStoreUrl;
    setScale(0);
    bindEvents();

    window.CCPlayer.onChange(renderTracks);
    window.CCPlayer.onError(function (msg) { toast(msg); });

    renderAll();
    loadEdition().catch(function (err) {
      console.error(err);
      state.failed = true;
      state.loaded = true;
      renderAll();
    });
  }

  init();
})();
