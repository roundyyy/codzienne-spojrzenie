#!/usr/bin/env python3
"""
Converts the app's curiosities CSV (DD/MM/YYYY,"text") into data/ciekawostki.js,
used by the "Ciekawostka dnia" card. A .js file (not .json) so the page also
works when index.html is opened straight from disk (file://).

Usage:
    python scripts/build_curiosities.py [path/to/ciekawostki.csv]

Default CSV path: the app project next to this folder.
"""

import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CSV = ROOT.parent / "app" / "src" / "main" / "res" / "raw" / "ciekawostki.csv"
OUTPUT = ROOT / "data" / "ciekawostki.js"


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CSV
    if not src.exists():
        print(f"CSV not found: {src}", file=sys.stderr)
        return 1

    facts: dict[str, str] = {}
    with src.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.reader(f):
            if len(row) >= 2 and re.fullmatch(r"\d{2}/\d{2}/\d{4}", row[0].strip()):
                facts[row[0].strip()] = row[1].strip()

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "/* Generated by scripts/build_curiosities.py - do not edit by hand. */\n"
        "window.CC_CURIOSITIES = " + json.dumps(facts, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8",
    )
    print(f"Saved {len(facts)} curiosities to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
